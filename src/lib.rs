/// A tiny stack string for formatted HUD numbers — no allocation.
struct StrBuf {
    bytes: [u8; 128],
    len: usize,
}

impl StrBuf {
    fn new() -> StrBuf {
        StrBuf {
            bytes: [0; 128],
            len: 0,
        }
    }

    fn push_str(&mut self, s: &str) {
        for &b in s.as_bytes() {
            if self.len < self.bytes.len() {
                self.bytes[self.len] = b;
                self.len += 1;
            }
        }
    }

    fn push_u32(&mut self, mut v: u32) {
        let mut digits = [0u8; 10];
        let mut n = 0;
        if v == 0 {
            self.push_str("0");
            return;
        }
        while v > 0 {
            digits[n] = b'0' + (v % 10) as u8;
            v /= 10;
            n += 1;
        }
        for i in (0..n).rev() {
            if self.len < self.bytes.len() {
                self.bytes[self.len] = digits[i];
                self.len += 1;
            }
        }
    }

    fn push_tenths_ms(&mut self, ms: i64) {
        // "6.0" for 6000 ms of ride time.
        let whole = (ms / 1000).max(0) as u32;
        let tenth = ((ms % 1000) / 100).max(0) as u32;
        self.push_u32(whole);
        self.push_str(".");
        self.push_u32(tenth);
    }

    fn as_str(&self) -> &str {
        core::str::from_utf8(&self.bytes[..self.len]).unwrap_or("")
    }
}

/// Bounded draw-list writer: one op per line ("r x y w h c" et al).
/// Past MAX_OPS or the buffer end, ops are dropped and counted — the
/// frame stays valid, never corrupt.
pub struct Writer<'a> {
    buf: &'a mut [u8],
    pos: usize,
    pub ops: usize,
    pub dropped: usize,
}

impl<'a> Writer<'a> {
    pub fn new(buf: &'a mut [u8]) -> Writer<'a> {
        Writer {
            buf,
            pos: 0,
            ops: 0,
            dropped: 0,
        }
    }

    fn raw(&mut self, s: &str) {
        if self.pos + s.len() > self.buf.len() {
            self.dropped += 1;
            return;
        }
        self.buf[self.pos..self.pos + s.len()].copy_from_slice(s.as_bytes());
        self.pos += s.len();
    }

    fn num(&mut self, v: i32) {
        let mut b = StrBuf::new();
        if v < 0 {
            b.push_str("-");
            b.push_u32(v.unsigned_abs());
        } else {
            b.push_u32(v as u32);
        }
        self.raw(b.as_str());
    }

    fn begin_op(&mut self, kind: &str) -> bool {
        if self.ops >= MAX_OPS {
            self.dropped += 1;
            return false;
        }
        self.ops += 1;
        self.raw(kind);
        true
    }

    pub fn rect(&mut self, x: i32, y: i32, w: i32, h: i32, c: u8) {
        if !self.begin_op("r") {
            return;
        }
        for v in [x, y, w, h, i32::from(c)] {
            self.raw(" ");
            self.num(v);
        }
        self.raw("\n");
    }

    pub fn circle(&mut self, x: i32, y: i32, r: i32, c: u8) {
        if !self.begin_op("c") {
            return;
        }
        for v in [x, y, r, i32::from(c)] {
            self.raw(" ");
            self.num(v);
        }
        self.raw("\n");
    }

    pub fn line(&mut self, x1: i32, y1: i32, x2: i32, y2: i32, c: u8, width: i32) {
        if !self.begin_op("l") {
            return;
        }
        for v in [x1, y1, x2, y2, i32::from(c), width] {
            self.raw(" ");
            self.num(v);
        }
        self.raw("\n");
    }

    pub fn tri(&mut self, pts: [(i32, i32); 3], c: u8) {
        if !self.begin_op("p") {
            return;
        }
        for v in [
            pts[0].0,
            pts[0].1,
            pts[1].0,
            pts[1].1,
            pts[2].0,
            pts[2].1,
            i32::from(c),
        ] {
            self.raw(" ");
            self.num(v);
        }
        self.raw("\n");
    }

    pub fn text(&mut self, x: i32, y: i32, size: i32, c: u8, s: &str) {
        if !self.begin_op("t") {
            return;
        }
        for v in [x, y, size, i32::from(c)] {
            self.raw(" ");
            self.num(v);
        }
        self.raw(" ");
        self.raw(s);
        self.raw("\n");
    }

    pub fn len(&self) -> usize {
        self.pos
    }

    pub fn is_empty(&self) -> bool {
        self.pos == 0
    }
}

