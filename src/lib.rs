//! withheld — Withheld core (Rust, wasm32-unknown-unknown).
//!
//! Tiger Style (tiger-style-rust): explicit contracts, bounded work,
//! disciplined ownership, no hidden behaviour. The core is a fixed-step
//! deterministic simulation: the shell calls `step` at 60 Hz with a fixed
//! dt; the core never reads a wall clock, never touches the DOM, and
//! reports everything it wants drawn as a draw list in a static buffer.
//!
//! Game: Yui's Governor game — edging as a control-systems game. Drive
//! rises while the player applies stimulus and decays when they do not.
//! A fixed threshold (the wall) caps every session contract: touch it
//! and the Governor cuts the drive and latches off. Winning is riding
//! the band just under the wall for the contracted time before the
//! countdown (the term, presented Counted Down) runs out. Begging is a
//! real input: a well-formed ask files a petition that improves the
//! NEXT session's schedule — never the current wall. Every trip is
//! written into the book: denial bookkeeping the shell persists.

// ---------------------------------------------------------------------------
// Domain constants
// ---------------------------------------------------------------------------

/// Logical canvas is 960x960 (program contract). All draw coordinates
/// are integer logical pixels.
pub const CANVAS_PX: i32 = 960;

/// Hard bound on draw ops per frame. The emitter drops (and counts) any
/// op past the bound instead of writing out of the buffer.
pub const MAX_OPS: usize = 1024;

/// Serialised draw-list buffer: one op per line, e.g. "r 10 20 30 40 2".
pub const DRAW_BUFFER_BYTES: usize = 64 * 1024;

/// Fixed step the shell is contracted to deliver.
pub const STEP_MS: u32 = 16;

/// Drive is measured in milli-units: 0..=1000.
pub const DRIVE_MAX: i32 = 1000;

/// A well-formed ask must be made from at or below wall − BEG_ZONE_MILLI
/// — begging from inside the band is noise, not a petition.
pub const BEG_ZONE_MILLI: i32 = 400;

/// Cooldown between filed asks, so the register cannot be spammed.
pub const BEG_COOLDOWN_MS: i64 = 4_000;

/// Petitions banked are capped; each is worth time and band next term.
pub const PETITION_CAP: u32 = 3;
pub const PETITION_BAND_MILLI: i32 = 15;
pub const PETITION_TIME_MS: i64 = 8_000;

