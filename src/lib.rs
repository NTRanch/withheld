// ---------------------------------------------------------------------------
// Tests: half validation, half adversarial (estate split). They drive the
// Game struct directly; the FFI is a thin shell over it.
// ---------------------------------------------------------------------------

#[cfg(test)]
mod tests {
    use super::*;

    fn play_game(level: u32) -> Game {
        let mut g = Game::new(42, false);
        assert!(g.start_level(level));
        g
    }

    fn steps(g: &mut Game, n: usize, inp: u32) {
        for _ in 0..n {
            g.step(STEP_MS, inp);
        }
    }

    /// Hysteresis rider, the human version of the demo policy.
    fn ride_step(g: &mut Game, hold: &mut bool) {
        if g.drive_milli >= g.eff_wall_milli - 25 {
            *hold = false;
        } else if g.drive_milli <= g.eff_band_lo_milli - 30 {
            *hold = true;
        }
        g.step(STEP_MS, if *hold { input::TAP } else { 0 });
    }

    // -- validation -----------------------------------------------------

    #[test]
    fn drive_rises_and_decays_at_contract_rates() {
        let mut g = play_game(0);
        steps(&mut g, 10, input::TAP);
        assert_eq!(g.drive_milli, 50); // 10 steps * rise 5
        steps(&mut g, 10, 0);
        assert_eq!(g.drive_milli, 20); // 50 - 10 * decay 3
    }

    #[test]
    fn riding_the_band_wins_the_term() {
        let mut g = play_game(0);
        let mut hold = false;
        let mut n = 0;
        while g.screen() != Screen::Victory && n < 5_000 {
            ride_step(&mut g, &mut hold);
            n += 1;
        }
        assert_eq!(g.screen(), Screen::Victory);
        assert!(g.ride_ms >= LEVELS[0].ride_needed_ms);
        assert_eq!(g.trips, 0);
    }

    #[test]
    fn well_formed_ask_files_and_moves_the_next_schedule() {
        let mut g = play_game(0);
        // From rest, unlatched, off cooldown: the textbook well-formed ask.
        g.step(STEP_MS, input::BEG);
        assert_eq!(g.petition_bits(), 1);
        assert_eq!(g.event_code(), event::ASK_FILED);
        // Filing again is capped by the register, so ride this term out
        // and confirm the NEXT term carries the bonus.
        let mut hold = false;
        let mut n = 0;
        while g.screen() != Screen::Victory && n < 5_000 {
            ride_step(&mut g, &mut hold);
            n += 1;
        }
        assert_eq!(g.screen(), Screen::Victory);
        assert!(g.start_level(1));
        assert_eq!(g.countdown_ms, LEVELS[1].term_ms + PETITION_TIME_MS);
        assert_eq!(
            g.eff_band_lo_milli,
            LEVELS[1].wall_milli - LEVELS[1].band_milli - PETITION_BAND_MILLI
        );
        assert_eq!(g.petition_bits(), 0); // consumed, not carried twice
        assert_eq!(g.eff_wall_milli, LEVELS[1].wall_milli); // wall unmoved
    }

    #[test]
    fn countdown_expiry_serves_the_term() {
        let mut g = play_game(0);
        let total = (LEVELS[0].term_ms / i64::from(STEP_MS)) as usize + 2;
        steps(&mut g, total, 0);
        assert_eq!(g.screen(), Screen::GameOver);
    }

    #[test]
    fn settings_and_petition_bridges_round_trip() {
        let mut g = Game::new(7, false);
        g.apply_settings(true, false);
        assert_eq!(g.settings_bits(), 1);
        g.apply_settings(false, true);
        assert_eq!(g.settings_bits(), 2);
        g.apply_settings(true, true);
        assert_eq!(g.settings_bits(), 3);
        g.apply_petition(2);
        assert_eq!(g.petition_bits(), 2);
    }

    #[test]
    fn demo_policy_completes_every_level() {
        for level in 0..LEVEL_COUNT {
            let mut g = Game::new(9000 + level, true);
            assert!(g.start_level(level));
            let max = ((LEVELS[level as usize].term_ms + 30_000) / i64::from(STEP_MS)) as usize;
            let mut n = 0;
            while g.screen() != Screen::Victory && n < max {
                g.step(STEP_MS, 0);
                n += 1;
            }
            assert_eq!(
                g.screen(),
                Screen::Victory,
                "demo failed level {}",
                level + 1
            );
            assert_eq!(g.trips, 0, "demo tripped the wall on level {}", level + 1);
        }
    }

    #[test]
    fn face_zones_track_the_drive() {
        let mut g = play_game(0);
        assert_eq!(g.face_zone(), FaceZone::Calm);
        steps(&mut g, 90, input::TAP); // 450 milli: past half the wall
        assert_eq!(g.face_zone(), FaceZone::Strained);
        steps(&mut g, 40, input::TAP); // 650 milli: inside the band
        assert_eq!(g.face_zone(), FaceZone::Riding);
    }

    // -- adversarial ------------------------------------------------------

    #[test]
    fn holding_through_the_wall_trips_and_latches() {
        let mut g = play_game(0);
        steps(&mut g, 200, input::TAP); // far more than enough to trip
        assert!(g.latched);
        assert_eq!(g.trips, 1);
        assert_eq!(g.term_added_ms, LEVELS[0].latch_ms);
        assert_eq!(g.face_zone(), FaceZone::Cut);
        // Stimulus is dead while latched: the drive never rises, and
        // no second trip can be written while the latch holds.
        let before = g.drive_milli;
        steps(&mut g, 10, input::TAP);
        assert!(g.drive_milli <= before);
        assert_eq!(g.trips, 1);
        // The latch releases after its term.
        let total = (LEVELS[0].latch_ms / i64::from(STEP_MS)) as usize + 2;
        steps(&mut g, total, 0);
        assert!(!g.latched);
    }

    #[test]
    fn drive_stays_bounded_under_sustained_spam() {
        let mut g = play_game(2); // gusts live, fastest rise
        for i in 0..20_000 {
            // Alternate full stimulus with beg mashing: worst case.
            let inp = if i % 3 == 0 {
                input::TAP | input::BEG
            } else {
                input::TAP
            };
            g.step(STEP_MS, inp);
            assert!(
                (0..=DRIVE_MAX).contains(&g.drive_milli),
                "drive escaped at step {i}"
            );
            if g.screen() != Screen::Play {
                break; // victory or game over are both lawful ends
            }
        }
        assert!(g.trips > 0, "spam that never trips is not spam");
    }

    #[test]
    fn malformed_asks_change_nothing() {
        // From inside the band: noise.
        let mut g = play_game(0);
        steps(&mut g, 130, input::TAP); // 650 milli, inside the band
        g.step(STEP_MS, input::BEG);
        assert_eq!(g.petition_bits(), 0);
        // While latched: noise.
        let mut g2 = play_game(0);
        steps(&mut g2, 200, input::TAP);
        assert!(g2.latched);
        g2.step(STEP_MS, input::BEG);
        assert_eq!(g2.petition_bits(), 0);
    }

    #[test]
    fn beg_spam_is_cooldown_and_cap_bounded() {
        let mut g = play_game(0);
        // Mash the register with fresh edges as fast as possible.
        for _ in 0..200 {
            g.step(STEP_MS, input::BEG);
            g.step(STEP_MS, 0);
        }
        // 200 edges in ~6.4 s of game time: cooldown 4 s, so at most 2
        // filings, and never above the cap.
        assert!(g.petition_bits() >= 1);
        assert!(g.petition_bits() <= 2);
        g.apply_petition(99);
        assert_eq!(g.petition_bits(), PETITION_CAP);
    }

    #[test]
    fn start_level_rejects_out_of_range() {
        let mut g = Game::new(3, false);
        assert!(!g.start_level(LEVEL_COUNT));
        assert!(!g.start_level(u32::MAX));
        assert_eq!(g.screen(), Screen::Gate); // untouched
    }

    #[test]
    fn oversized_dt_is_clamped() {
        let mut g = play_game(0);
        g.step(100_000, 0);
        // One step may consume at most 50 ms of the term.
        assert_eq!(g.countdown_ms, LEVELS[0].term_ms - 50);
    }

    #[test]
    fn same_seed_same_inputs_same_frame() {
        let mut a = play_game(2);
        let mut b = play_game(2);
        let mut rng = Rng::new(1234);
        for _ in 0..5_000 {
            let inp = rng.next_u32() % 128;
            a.step(STEP_MS, inp);
            b.step(STEP_MS, inp);
        }
        let mut ba = vec![0u8; DRAW_BUFFER_BYTES];
        let mut bb = vec![0u8; DRAW_BUFFER_BYTES];
        let na = a.render(&mut ba);
        let nb = b.render(&mut bb);
        assert_eq!(na, nb);
        assert_eq!(&ba[..na], &bb[..nb]);
    }

    #[test]
    fn every_screen_renders_a_bounded_well_formed_list() {
        let screens = [
            Screen::Gate,
            Screen::Title,
            Screen::Howto,
            Screen::Settings,
            Screen::Victory,
            Screen::GameOver,
        ];
        for s in screens {
            let mut g = Game::new(11, false);
            g.screen = s;
            let mut buf = vec![0u8; DRAW_BUFFER_BYTES];
            let n = g.render(&mut buf);
            assert!(n < DRAW_BUFFER_BYTES);
            let text = core::str::from_utf8(&buf[..n]).unwrap();
            let mut ops = 0;
            for line in text.lines() {
                assert!(
                    matches!(line.chars().next(), Some('r' | 'c' | 'l' | 'p' | 't')),
                    "bad op: {line}"
                );
                ops += 1;
            }
            assert!(ops <= MAX_OPS);
            assert!(ops > 0);
        }
        // Play + pause render too.
        let mut g = play_game(1);
        steps(&mut g, 120, input::TAP);
        let mut buf = vec![0u8; DRAW_BUFFER_BYTES];
        assert!(g.render(&mut buf) > 0);
        g.step(STEP_MS, input::PAUSE);
        assert_eq!(g.screen(), Screen::Pause);
        assert!(g.render(&mut buf) > 0);
    }
}
