/// Screens. The core owns all screens as draw lists; the shell only
/// interprets them and watches transitions for its records.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
#[repr(u8)]
pub enum Screen {
    Gate = 0,     // 18+ gate (first screen, always)
    Title = 1,    // menu + term picker
    Howto = 2,    // the session contract, in words
    Play = 3,     // the Governor session itself
    Pause = 4,    // session held
    Settings = 5, // gusts + text size; reachable before any play
    Victory = 6,  // the term was ridden out
    GameOver = 7, // the countdown served the term first
}

/// Her expression is a keyframe over the drive's position relative to
/// the wall — posture AND expression move together (Séraphine standard).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum FaceZone {
    Calm,     // drive low: resting, composed
    Strained, // drive rising: anticipation, breath held
    Riding,   // inside the band: F-03-class edge, controlled
    Cut,      // latched after a trip: the Governor has spoken
}

/// One session contract: the preset IS the level (PLANNING: threshold
/// presets per session contract).
#[derive(Clone, Copy, Debug)]
pub struct Level {
    pub name: &'static str,
    pub wall_milli: i32,     // the fixed threshold
    pub band_milli: i32,     // width of the ride band under the wall
    pub rise_per_step: i32,  // drive gained per step while stimulated
    pub decay_per_step: i32, // drive lost per step while not
    pub ride_needed_ms: i64, // time in band that completes the term
    pub term_ms: i64,        // the countdown, before petition bonuses
    pub latch_ms: i64,       // lockout after a trip; written into the book
    pub gusts: bool,         // disturbance schedule active
}

